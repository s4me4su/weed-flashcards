// ---------------------------------------------------------------------------
// Swipeable top card (drag with mouse or finger, tap to flip)
// ---------------------------------------------------------------------------

enum SwipeDirection { left, right }

class SwipeCard extends StatefulWidget {
  const SwipeCard({
    super.key,
    required this.card,
    required this.size,
    required this.onSwipe,
  });

  final FlashCard card;
  final Size size;
  final void Function(FlashCard card, SwipeDirection direction) onSwipe;

  @override
  State<SwipeCard> createState() => SwipeCardState();
}

class SwipeCardState extends State<SwipeCard>
    with SingleTickerProviderStateMixin {
  late final AnimationController _flyCtrl = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 300),
  );
  Animation<Offset>? _flyTween;
  Offset _drag = Offset.zero;
  bool _flipped = false;
  bool _throwing = false;
  SwipeDirection? _throwDir;

  /// Drag distance that counts as a swipe. Never zero, so the stamp opacities
  /// below can never divide by zero.
  double get _swipeThreshold => math.max(1.0, widget.size.width * 0.28);

  @override
  void initState() {
    super.initState();
    _flyCtrl.addListener(() {
      final tween = _flyTween;
      if (tween != null) setState(() => _drag = tween.value);
    });
    _flyCtrl.addStatusListener((status) {
      if (status == AnimationStatus.completed && _throwing) {
        _throwing = false;
        widget.onSwipe(widget.card, _throwDir!);
      }
    });
  }

  @override
  void didUpdateWidget(covariant SwipeCard oldWidget) {
    super.didUpdateWidget(oldWidget);
    // The GlobalKey is reused for the next card in the stack: reset state.
    if (oldWidget.card.id != widget.card.id) {
      _flyCtrl.stop();
      _flyTween = null;
      _throwing = false;
      _throwDir = null;
      _drag = Offset.zero;
      _flipped = false;
    }
  }

  @override
  void dispose() {
    _flyCtrl.dispose();
    super.dispose();
  }

  /// Programmatic swipe for the on-screen buttons and the arrow keys.
  void swipe(SwipeDirection dir) {
    if (_throwing) return;
    final dx = dir == SwipeDirection.right
        ? widget.size.width * 1.4
        : -widget.size.width * 1.4;
    _launch(dir, Offset(dx, _drag.dy + 40));
  }

  /// Turns the card over in place (tap, or the space bar on the desktop).
  void toggleFlip() {
    if (_throwing) return;
    setState(() => _flipped = !_flipped);
  }

  void _onPanUpdate(DragUpdateDetails details) {
    if (_throwing) return;
    setState(() => _drag += details.delta);
  }

  void _onPanEnd(DragEndDetails details) {
    if (_throwing) return;
    final velocity = details.velocity.pixelsPerSecond.dx;
    final farEnough = _drag.dx.abs() > _swipeThreshold;
    final flung = velocity.abs() > 700 && velocity.sign == _drag.dx.sign;
    if (farEnough || flung) {
      final dir = _drag.dx > 0 ? SwipeDirection.right : SwipeDirection.left;
      final dx = dir == SwipeDirection.right
          ? widget.size.width * 1.4
          : -widget.size.width * 1.4;
      _launch(dir, Offset(dx, _drag.dy + 60));
    } else {
      _snapBack();
    }
  }

  void _launch(SwipeDirection dir, Offset end) {
    _throwing = true;
    _throwDir = dir;
    _flyTween = Tween<Offset>(begin: _drag, end: end).animate(
      CurvedAnimation(parent: _flyCtrl, curve: Curves.easeInCubic),
    );
    _flyCtrl.forward(from: 0);
  }

  void _snapBack() {
    _flyTween = Tween<Offset>(begin: _drag, end: Offset.zero).animate(
      CurvedAnimation(parent: _flyCtrl, curve: Curves.elasticOut),
    );
    _flyCtrl.forward(from: 0);
  }

  @override
  Widget build(BuildContext context) {
    final width = widget.size.width;
    final progressRight = (_drag.dx / _swipeThreshold).clamp(0.0, 1.0);
    final progressLeft = (-_drag.dx / _swipeThreshold).clamp(0.0, 1.0);
    final rotation = (_drag.dx / width).clamp(-0.4, 0.4) * 0.35;

    return SizedBox(
      width: widget.size.width,
      height: widget.size.height,
      child: Transform.translate(
        offset: _drag,
        child: Transform.rotate(
          angle: rotation,
          child: Stack(
            children: <Widget>[
              GestureDetector(
                behavior: HitTestBehavior.opaque,
                onTap: toggleFlip,
                onPanUpdate: _onPanUpdate,
                onPanEnd: _onPanEnd,
                child: CardFace(
                  card: widget.card,
                  size: widget.size,
                  flipped: _flipped,
                  interactive: true,
                ),
              ),
              Positioned(
                left: 16,
                top: 20,
                child: IgnorePointer(
                  child: Opacity(
                    opacity: progressLeft,
                    child: const _Stamp(
                      label: 'REVIEW',
                      color: Color(0xFFFF4D6D),
                      angle: -0.25,
                    ),
                  ),
                ),
              ),
              Positioned(
                right: 16,
                top: 20,
                child: IgnorePointer(
                  child: Opacity(
                    opacity: progressRight,
                    child: const _Stamp(
                      label: 'KNOWN',
                      color: Color(0xFF19C37D),
                      angle: 0.25,
                    ),
                  ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

