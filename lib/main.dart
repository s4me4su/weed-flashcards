const String kAllFilter = 'all';

/// Filter options: the whole deck, then every family in the booklet,
/// alphabetically.
final List<String> kFilterOrder = <String>[
  kAllFilter,
  ...kFamilies.keys.toList()..sort(),
];

String filterLabel(String filter) =>
    filter == kAllFilter ? 'All weeds' : filter;

bool cardMatches(FlashCard card, String filter) =>
    filter == kAllFilter || card.family == filter;

/// How many cards a filter offers - shown next to each entry in the dropdown.
int countForFilter(String filter) => filter == kAllFilter
    ? kDeck.length
    : kDeck.where((c) => cardMatches(c, filter)).length;

// ---------------------------------------------------------------------------
// Study screen (all state kept here with setState)
// ---------------------------------------------------------------------------

class StudyScreen extends StatefulWidget {
  const StudyScreen({super.key});

  @override
  State<StudyScreen> createState() => _StudyScreenState();
}

class _StudyScreenState extends State<StudyScreen> with WidgetsBindingObserver {
  List<FlashCard> _deck = List<FlashCard>.of(kDeck);
  int _index = 0;
  final Set<String> _forReview = <String>{};
  final math.Random _rng = math.Random();
  final GlobalKey<SwipeCardState> _topCardKey = GlobalKey<SwipeCardState>();

  /// Active family filter ('all' = the whole deck).
  String _filter = kAllFilter;

  /// Debounced auto-save: the deck is written a moment after any change, so
  /// closing the app never loses work.
  Timer? _saveTimer;

  /// True when something has changed that is not on disk yet.
  bool _dirty = false;

  /// Where the save actually lives (a file next to the exe on Windows, the app's
  /// files dir on Android, localStorage in a browser). Worked out once and shown
  /// in the Save tooltip and in save errors, so "where is my progress?" -
  /// or "why did saving fail?" - has an answer.
  late final String _deckLocation = deckLocation();

  bool get _deckFinished => _index >= _deck.length;

  /// The cards in [kDeck] that pass the current filter.
  List<FlashCard> _filteredDeck() => _filter == kAllFilter
      ? List<FlashCard>.of(kDeck)
      : kDeck.where((c) => cardMatches(c, _filter)).toList();

  void _applyFilter(String filter) {
    setState(() {
      _filter = filter;
      _deck = _filteredDeck();
      _index = 0;
      // Review marks are deliberately kept: they are per card, and losing them
      // because you peeked at another family is annoying.
    });
    _scheduleSave();
  }

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
    _restoreSaved();
  }

  @override
  void dispose() {
    _saveTimer?.cancel();
    WidgetsBinding.instance.removeObserver(this);
    super.dispose();
  }

  /// Android sends this before the app is backgrounded or killed, the web
  /// when the tab is hidden - so leaving the app saves the deck by itself.
  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (_dirty &&
        (state == AppLifecycleState.paused ||
            state == AppLifecycleState.hidden ||
            state == AppLifecycleState.detached)) {
      _saveNow(silent: true);
    }
  }

  String _encode() => jsonEncode(<String, dynamic>{
        'v': 1,
        'order': _deck.map((c) => c.id).toList(),
        'index': _index,
        'review': _forReview.toList(),
        'filter': _filter,
      });

  void _scheduleSave() {
    _dirty = true;
    _saveTimer?.cancel();
    _saveTimer = Timer(const Duration(milliseconds: 700),
        () => _saveNow(silent: true));
  }

  Future<void> _saveNow({bool silent = false}) async {
    _saveTimer?.cancel();
    final payload = _encode();
    try {
      await writeDeck(payload);
      _dirty = false;
    } catch (e) {
      if (!mounted) return;
      _toast('Could not save the deck to $_deckLocation: $e');
      return;
    }
    if (silent || !mounted) return;
    _toast('Deck saved — it will reopen right here');
  }

  void _toast(String message) {
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(SnackBar(content: Text(message)));
  }

  /// Reopens the last saved deck: order, position, review marks, the family
  /// filter and any cards that were removed.
  Future<void> _restoreSaved() async {
    final String? raw;
    try {
      raw = await readDeck();
    } catch (_) {
      return;
    }
    if (raw == null || raw.isEmpty || !mounted) return;
    try {
      final decoded = jsonDecode(raw);
      if (decoded is! Map) return; // not our format - ignore it
      final data = decoded.cast<String, dynamic>();

      // A filter that is not offered any more (an old save file, or a family
      // that has left the booklet) would make the dropdown assert, so fall
      // back to the whole deck.
      final savedFilter = (data['filter'] as String?) ?? kAllFilter;
      final filter =
          kFilterOrder.contains(savedFilter) ? savedFilter : kAllFilter;

      final byId = <String, FlashCard>{for (final c in kDeck) c.id: c};
      var order = <FlashCard>[];
      for (final id in (data['order'] as List? ?? const [])
          .whereType<String>()) {
        final card = byId[id];
        if (card != null) order.add(card);
      }
      if (filter != kAllFilter) {
        order = order.where((c) => cardMatches(c, filter)).toList();
      }
      if (order.isEmpty) return;

      final kept = <String>{for (final c in order) c.id};
      final review = <String>{
        for (final id in (data['review'] as List? ?? const [])
            .whereType<String>())
          if (kept.contains(id)) id,
      };
      final savedIndex = (data['index'] as num?)?.toInt() ?? 0;

      if (!mounted) return; // the widget went away while we were reading
      setState(() {
        _filter = filter;
        _deck = order;
        _index = savedIndex.clamp(0, order.length);
        _forReview
          ..clear()
          ..addAll(review);
      });
      _toast('Saved deck restored — ${order.length} cards');
    } catch (_) {
      // Corrupt or unreadable save: start with the full deck rather than
      // refusing to open.
    }
  }

  /// Removes the current card from this deck entirely, with an undo.
  void _deleteCurrent() {
    if (_deckFinished) return;
    final card = _deck.removeAt(_index);
    final wasAt = _index;
    _forReview.remove(card.id);
    if (_index > _deck.length) _index = _deck.length;
    setState(() {});
    _scheduleSave();
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(SnackBar(
        content: Text('Removed "${card.title}" from this deck'),
        action: SnackBarAction(
          label: 'UNDO',
          onPressed: () {
            setState(() {
              _deck.insert(wasAt.clamp(0, _deck.length), card);
              _index = wasAt;
            });
            _scheduleSave();
          },
        ),
      ));
  }

  void _reshuffle() {
    setState(() {
      _deck = _filteredDeck()..shuffle(_rng);
      _index = 0;
      _forReview.clear();
    });
    _scheduleSave();
  }

  void _restartInOrder() {
    setState(() {
      _deck = _filteredDeck();
      _index = 0;
      _forReview.clear();
    });
    _scheduleSave();
  }

  void _handleSwipe(FlashCard card, SwipeDirection dir) {
    setState(() {
      if (dir == SwipeDirection.left) {
        _forReview.add(card.id);
      } else {
        _forReview.remove(card.id);
      }
      _index += 1;
    });
    _scheduleSave();
    _precacheAhead();
  }

  /// Pulls the next card's two images in while you are still looking at this
  /// one, so the next card appears instantly (most noticeable on the web
  /// build, where images are fetched per card).
  void _precacheAhead() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!mounted) return;
      for (var i = _index; i < math.min(_index + 2, _deck.length); i++) {
        final card = _deck[i];
        precacheImage(AssetImage(card.frontAsset), context);
        precacheImage(AssetImage(card.backAsset), context);
      }
    });
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: LayoutBuilder(
          builder: (context, bar) {
            // A phone screen is ~390 px wide, so the filter dropdown only
            // gets what the counter and the two action buttons leave over.
            final ddWidth = (bar.maxWidth - 190).clamp(70.0, 170.0);
            return Row(
              mainAxisSize: MainAxisSize.min,
              children: <Widget>[
                Flexible(
                  child: Column(
                    mainAxisSize: MainAxisSize.min,
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: <Widget>[
                      Text(
                        _deckFinished
                            ? 'Deck complete'
                            : 'Card ${_index + 1} of ${_deck.length}',
                        overflow: TextOverflow.ellipsis,
                        softWrap: false,
                      ),
                      if (_forReview.isNotEmpty)
                        Text(
                          '${_forReview.length} marked for review',
                          overflow: TextOverflow.ellipsis,
                          softWrap: false,
                          style: const TextStyle(
                              fontSize: 11, color: Colors.white70),
                        ),
                    ],
                  ),
                ),
                const SizedBox(width: 10),
                SizedBox(
                  width: ddWidth,
                  child: _buildFilterDropdown(),
                ),
              ],
            );
          },
        ),
        actions: <Widget>[
          IconButton(
            tooltip: 'Save deck now (it also saves by itself)\n'
                'Saved to: $_deckLocation',
            icon: const Icon(Icons.save_alt),
            iconSize: 28,
            onPressed: () => _saveNow(),
          ),
          IconButton(
            tooltip: 'Reset / Reshuffle (full deck, removed cards return)',
            icon: const Icon(Icons.refresh),
            iconSize: 28,
            onPressed: _reshuffle,
          ),
        ],
      ),
      // SafeArea: on a phone the button row must sit above the navigation
      // bar / home indicator, not underneath it.
      body: SafeArea(
        bottom: true,
        child: Focus(
          autofocus: true,
          onKeyEvent: _onKey,
          child: Column(
            children: <Widget>[
              LinearProgressIndicator(
                minHeight: 3,
                // An empty deck (every card removed) would divide by zero.
                value: _deck.isEmpty
                    ? 1.0
                    : (_index / _deck.length).clamp(0.0, 1.0),
              ),
              Expanded(
                child: LayoutBuilder(
                  builder: (context, constraints) => _deckFinished
                      ? _buildSummary()
                      : _buildStack(_cardSizeFor(constraints)),
                ),
              ),
              _buildActionBar(),
            ],
          ),
        ),
      ),
    );
  }

  /// Keyboard shortcuts for the desktop build (or a bluetooth keyboard on a
  /// phone): arrows swipe, space flips.
  KeyEventResult _onKey(FocusNode node, KeyEvent event) {
    if (event is! KeyDownEvent && event is! KeyRepeatEvent) {
      return KeyEventResult.ignored;
    }
    if (_deckFinished) return KeyEventResult.ignored;
    final SwipeCardState? card = _topCardKey.currentState;
    final code = event.logicalKey;
    if (code == LogicalKeyboardKey.arrowLeft) {
      card?.swipe(SwipeDirection.left);
      return KeyEventResult.handled;
    }
    if (code == LogicalKeyboardKey.arrowRight) {
      card?.swipe(SwipeDirection.right);
      return KeyEventResult.handled;
    }
    if (code == LogicalKeyboardKey.space) {
      card?.toggleFlip();
      return KeyEventResult.handled;
    }
    return KeyEventResult.ignored;
  }

  /// Compact "Label ⌄" dropdown in the app bar: all 45 weeds, or one of the
  /// plant families printed in the booklet.
