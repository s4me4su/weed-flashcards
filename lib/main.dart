    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10),
      decoration: BoxDecoration(
        color: Colors.white.withValues(alpha: 0.12),
        borderRadius: BorderRadius.circular(10),
        border: Border.all(color: Colors.white.withValues(alpha: 0.35)),
      ),
      child: DropdownButtonHideUnderline(
        child: DropdownButton<String>(
          value: _filter,
          borderRadius: BorderRadius.circular(10),
          dropdownColor: Colors.white,
          menuMaxHeight: 460,
          isDense: true,
          // Let the label shrink (with "...") instead of pushing the row over.
          isExpanded: true,
          style: const TextStyle(
            color: Colors.black,
            fontSize: 14,
            fontWeight: FontWeight.w600,
          ),
          // What the button itself shows: current family. The chevron comes
          // from `icon` below, so it is not drawn twice.
          selectedItemBuilder: (context) => <Widget>[
            for (final f in kFilterOrder)
              Row(
