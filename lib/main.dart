                  for (final c in byFamily[family]!)
                    Chip(label: Text(c.title)),
                ],
              ),
            ],
            const SizedBox(height: 24),
            FilledButton.icon(
              onPressed: _reshuffle,
              icon: const Icon(Icons.shuffle),
              label: const Text('Reshuffle & restart'),
