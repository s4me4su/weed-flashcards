class CardFace extends StatelessWidget {
  const CardFace({
    super.key,
    required this.card,
    required this.size,
    required this.flipped,
    required this.interactive,
  });

  final FlashCard card;
  final Size size;
  final bool flipped;
  final bool interactive;

  @override
  Widget build(BuildContext context) {
    // FRONT: the booklet page with the header band painted out, so the name is
    // not on it. This is the side shown first. The image fills the whole card;
    // the hint floats over it so nothing shrinks the page.
    final front = Stack(
      fit: StackFit.expand,
      children: <Widget>[
        _CardImage(asset: card.frontAsset, size: size),
        if (interactive)
          Align(
            alignment: Alignment.bottomCenter,
            child: Padding(
              padding: const EdgeInsets.only(bottom: 10),
              child: Container(
                padding:
                    const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                decoration: BoxDecoration(
                  color: Colors.black.withValues(alpha: 0.35),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: const Text(
                  'TAP TO FLIP',
                  style: TextStyle(
                    fontSize: 11,
                    color: Colors.white,
                    letterSpacing: 2,
                  ),
                ),
              ),
            ),
          ),
      ],
    );

    // BACK: the page exactly as printed - common name, scientific name and
    // plant family are all part of the picture, so nothing is overlaid.
    final back = _CardImage(asset: card.backAsset, size: size);

    return Container(
      width: size.width,
      height: size.height,
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(20),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.35),
            blurRadius: 24,
            offset: const Offset(0, 12),
          ),
        ],
      ),
      clipBehavior: Clip.antiAlias,
      child: interactive
          // Keyed by card id so a recycled SwipeCard never animates the
          // previous card's flip state onto the new card.
          ? FlipCard(
              key: ValueKey<String>(card.id),
              flipped: flipped,
              front: front,
              back: back,
            )
          : front,
    );
  }
}

class _CardImage extends StatelessWidget {
  const _CardImage({required this.asset, required this.size});

  final String asset;
  final Size size;

  @override
  Widget build(BuildContext context) {
    return Image.asset(
      asset,
      fit: BoxFit.contain,
      filterQuality: FilterQuality.medium,
      cacheWidth:
          (size.width * MediaQuery.devicePixelRatioOf(context)).round(),
      errorBuilder: (context, error, stackTrace) => Center(
        child: Padding(
          padding: const EdgeInsets.all(16),
          child: Text(
            'Missing asset:\n$asset',
            textAlign: TextAlign.center,
            style: const TextStyle(color: Colors.black45, fontSize: 13),
          ),
        ),
      ),
    );
  }
}

// ---------------------------------------------------------------------------
// 180-degree flip animation
// ---------------------------------------------------------------------------

class FlipCard extends StatefulWidget {
  const FlipCard({
    super.key,
    required this.flipped,
    required this.front,
    required this.back,
  });

  final bool flipped;
  final Widget front;
  final Widget back;

  @override
  State<FlipCard> createState() => _FlipCardState();
}

class _FlipCardState extends State<FlipCard>
    with SingleTickerProviderStateMixin {
  late final AnimationController _ctrl = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 550),
  );

  @override
  void initState() {
    super.initState();
    if (widget.flipped) _ctrl.value = 1.0;
  }

  @override
  void didUpdateWidget(covariant FlipCard oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (widget.flipped != oldWidget.flipped) {
      if (widget.flipped) {
        _ctrl.forward(from: 0);
      } else {
        _ctrl.reverse(from: 1);
      }
    }
  }

  @override
  void dispose() {
    _ctrl.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: _ctrl,
      builder: (context, _) {
        final angle = _ctrl.value * math.pi;
        final showFront = angle <= math.pi / 2;
        final matrix = Matrix4.identity()
          ..setEntry(3, 2, 0.0015) // perspective for a real 3D feel
          ..rotateY(showFront ? angle : angle - math.pi);
        return Transform(
          alignment: Alignment.center,
          transform: matrix,
          child: showFront ? widget.front : widget.back,
        );
      },
    );
  }
}
