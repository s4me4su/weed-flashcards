  final String title;
  final int number;
  final String sci;
  final String family;

  /// Front: the booklet page with the header band painted out, so the name is
  /// not visible. This is the side you see first.
  String get frontAsset => 'assets/front/$id.jpg';

  /// Back: the same page with nothing removed - the name, the scientific name
  /// and the plant family are all printed on it.
  String get backAsset => 'assets/back/$id.jpg';

  /// Common name of this card's family, e.g. 'Oleaceae' -> 'olive'.
  String get familyCommon => kFamilies[family] ?? '';

  /// '13. Salvinia' - used where a card is listed rather than shown.
  String get label => '$number. $title';
}

