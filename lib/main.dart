            for (final f in kFilterOrder)
              DropdownMenuItem<String>(
                value: f,
                child: Text('${filterLabel(f)}  (${countForFilter(f)})'),
              ),
          ],
          onChanged: (v) {
            if (v != null && v != _filter) _applyFilter(v);
          },
        ),
      ),
    );
  }

  /// The largest card that fits the space left between the top bar and the
  /// buttons, keeping the A4 portrait ratio of the booklet pages.
  Size _cardSizeFor(BoxConstraints c) {
    const aspect = 1.414; // A4 portrait
    // Never hand back a negative (asserts) or infinite (asserts) size: a very
    // short window is unusual but possible on the desktop build.
    double side(double v, double fallback) =>
        v.isFinite && v > 0 ? v : fallback;
    final availW = side(c.maxWidth - 12, 320);
    final availH = side(c.maxHeight - 12, 452);
    var h = availH;
    var w = h / aspect;
    if (w > availW) {
      w = availW;
      h = w * aspect;
    }
    return Size(w, h);
  }

  /// Renders up to three stacked cards; only the top one is interactive.
  Widget _buildStack(Size cardSize) {
    final remaining = _deck.length - _index;
    final visibleCount = math.min(3, remaining);
    final stack = <Widget>[];

    // Draw deepest card first so the top card ends up on top.
    for (var depth = visibleCount - 1; depth >= 0; depth--) {
      final card = _deck[_index + depth];
      final Widget child = depth == 0
          ? SwipeCard(
              key: _topCardKey,
              card: card,
              size: cardSize,
              onSwipe: _handleSwipe,
            )
          : CardFace(
              card: card,
              size: cardSize,
              flipped: false,
              interactive: false,
            );

      stack.add(
        Center(
          child: Transform.translate(
            offset: Offset(0, depth * 12.0),
            child: Transform.scale(
              scale: 1.0 - depth * 0.04,
              child: Opacity(
                opacity: 1.0 - depth * 0.15,
                child: child,
              ),
            ),
          ),
        ),
      );
    }

    return Stack(alignment: Alignment.center, children: stack);
  }

  Widget _buildActionBar() {
    return Padding(
